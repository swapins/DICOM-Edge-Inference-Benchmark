"""Generate a self-contained Kaggle notebook from the local research source tree.

This makes the Windows VS Code checkout the single source of truth. Only
explicitly allowed source/test/docs files are packed; no datasets or secrets.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import io
import json
from pathlib import Path
import re
import textwrap
import zipfile

PROJECT_FOLDER = 'DICOM-Edge-Inference-Benchmark'
KERNEL_SLUG = 'dicom-edge-inference-benchmark'
KERNEL_FILE = 'DICOM_Edge_Kaggle.ipynb'


def source_paths(root: Path) -> list[Path]:
    candidates = [root / name for name in ('pyproject.toml', 'README.md', 'LICENSE')]
    for section, pattern in (
        ('src', '*.py'), ('tests', 'test_*.py'),
        ('scripts', '*.py'), ('notebooks', '*.ipynb'), ('docs', '*.md'),
    ):
        base = root / section
        if base.is_dir():
            candidates.extend(base.rglob(pattern))
    files = sorted({p.resolve() for p in candidates if p.is_file() and not p.is_symlink()})
    for path in files:
        path.relative_to(root.resolve())
    for required in ('pyproject.toml', 'scripts/run_kaggle.py'):
        if not (root / required).is_file():
            raise FileNotFoundError(f'Missing required project source: {required}')
    return files


def pack_sources(root: Path) -> bytes:
    buffer = io.BytesIO()
    manifest: dict[str, str] = {}
    with zipfile.ZipFile(buffer, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=8) as archive:
        for path in source_paths(root):
            relative = path.relative_to(root).as_posix()
            content = path.read_bytes()
            archive.writestr(f'{PROJECT_FOLDER}/{relative}', content)
            manifest[relative] = hashlib.sha256(content).hexdigest()
        archive.writestr(
            f'{PROJECT_FOLDER}/source_manifest.json',
            json.dumps(manifest, sort_keys=True, indent=2) + '\n',
        )
    return buffer.getvalue()


def build_notebook(source_notebook: Path, payload: bytes, profile: str) -> dict:
    notebook = json.loads(source_notebook.read_text(encoding='utf-8'))
    if len(notebook['cells']) < 17:
        raise ValueError('Source notebook structure unexpectedly changed; inspect before regenerating.')
    b64 = base64.b64encode(payload).decode('ascii')
    lines = '\n'.join(f'    {segment!r}' for segment in textwrap.wrap(b64, 110))
    new_cell = f'''from pathlib import Path
import base64, io, zipfile, hashlib, shutil
WORK_ROOT = Path('/kaggle/working')
PROJECT = WORK_ROOT / {PROJECT_FOLDER!r}
# Source produced from the local VS Code checkout; do not edit this generated cell.
SOURCE_BASE64 = (\n{lines}\n)
source_zip = base64.b64decode(SOURCE_BASE64)
expected = {hashlib.sha256(payload).hexdigest()!r}
assert hashlib.sha256(source_zip).hexdigest() == expected, 'Source bundle checksum mismatch'
with zipfile.ZipFile(io.BytesIO(source_zip)) as source:
    source.extractall(WORK_ROOT)
assert (PROJECT / 'pyproject.toml').exists(), 'Embedded source extraction failed'
print('Loaded local source bundle:', len(source_zip), 'bytes')
print('Bundle SHA256:', expected)
'''
    def set_source(cell: dict, new_content: str) -> None:
        cell['source'] = new_content.splitlines(keepends=True)
    set_source(notebook['cells'][1],
        f'PROFILE = {profile!r}  # Change locally and regenerate to switch pilot/full\n'
        "RUN_PACKAGE_TESTS = True\n"
        "HIGH_DICOM_PIN = 'd42f664006a9cd2194eda0bf5b1cf0fa2fb0188e'\n"
    )
    set_source(notebook['cells'][4],
        '## 2. Load the locally authored source bundle\n\n'
        'This notebook is generated by `scripts/prepare_kaggle_kernel.py` from the VS Code project. '
        'No Kaggle Dataset upload or GitHub repository is required for the research source.\n'
    )
    set_source(notebook['cells'][5], new_cell)
    for cell in notebook['cells']:
        if cell['cell_type'] == 'code':
            cell['execution_count'] = None
            cell['outputs'] = []
    return notebook


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--owner', required=True, help='Your Kaggle username/slug; NOT your email or token')
    parser.add_argument('--profile', choices=('pilot', 'full'), default='pilot')
    parser.add_argument('--output-dir', type=Path, default=Path('kaggle'))
    parser.add_argument('--private', action='store_true', default=True)
    args = parser.parse_args(argv)
    if not re.fullmatch(r'[A-Za-z0-9_-]{2,64}', args.owner):
        parser.error('Provide only the Kaggle username, e.g., kaggle-user123 (not credentials).')
    root = Path(__file__).resolve().parent.parent
    notebook_source = root / 'notebooks' / 'Kaggle_GPU_Benchmark.ipynb'
    if not notebook_source.exists():
        raise FileNotFoundError(f'Missing notebook source: {notebook_source}')
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    payload = pack_sources(root)
    notebook = build_notebook(notebook_source, payload, args.profile)
    destination = out / KERNEL_FILE
    destination.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + '\n', encoding='utf-8')
    meta = {
        'id': f'{args.owner}/{KERNEL_SLUG}',
        'title': 'DICOM Edge Inference Benchmark',
        'code_file': KERNEL_FILE,
        'language': 'python',
        'kernel_type': 'notebook',
        'is_private': 'true',
        'enable_gpu': 'true',
        'enable_internet': 'true',
        'machine_shape': 'NvidiaTeslaT4',
        'dataset_sources': [],
        'competition_sources': [],
        'kernel_sources': [],
        'model_sources': [],
    }
    (out / 'kernel-metadata.json').write_text(json.dumps(meta, indent=2) + '\n', encoding='utf-8')
    print(f'Kaggle source built from local repository: {len(source_paths(root))} files')
    print(f'Notebook: {destination}')
    print(f'Metadata: {out / "kernel-metadata.json"}')
    print(f'Kaggle ID: {meta["id"]} (private; GPU T4 x2 enabled)')
    print('Run: kaggle kernels push -p kaggle --accelerator NvidiaTeslaT4')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
